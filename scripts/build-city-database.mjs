// Derive the mobile database from the pinned GeoNames JSON; never download new content.
import {DatabaseSync} from 'node:sqlite';
import {createRequire} from 'node:module';
import {readFileSync,mkdirSync,rmSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
globalThis.require=createRequire(new URL('../src/domain/cities.ts',import.meta.url));
const {normalizeCitySearch}=await import('../src/domain/cities.ts');
const root=new URL('../assets/cities/',import.meta.url);mkdirSync(root,{recursive:true});
const source=JSON.parse(readFileSync(new URL('../src/data/cities.json',import.meta.url),'utf8')).flat();
const hash=createHash('sha256').update(JSON.stringify(source)).digest('hex');
const name=`cities-${hash.slice(0,12)}.db`,path=fileURLToPath(new URL(name,root));rmSync(path,{force:true});
const db=new DatabaseSync(path);
try{
  db.exec('PRAGMA journal_mode=OFF; PRAGMA synchronous=OFF; BEGIN; CREATE TABLE cities (id INTEGER PRIMARY KEY, ordinal INTEGER NOT NULL, name TEXT NOT NULL, arabicName TEXT, asciiName TEXT, countryCode TEXT NOT NULL, latitude REAL NOT NULL, longitude REAL NOT NULL, timeZone TEXT, searchNames TEXT NOT NULL);');
  const insert=db.prepare('INSERT INTO cities VALUES(?,?,?,?,?,?,?,?,?,?)');
  source.forEach((city,ordinal)=>{const aliases=[...new Set([city.name,city.asciiName,city.arabicName].filter(Boolean).map(normalizeCitySearch))];insert.run(city.id,ordinal,city.name,city.arabicName??null,city.asciiName??null,city.countryCode,city.latitude,city.longitude,city.timeZone??null,`\u001f${aliases.join('\u001f')}\u001f`);});
  db.exec('CREATE INDEX cities_country ON cities(countryCode,ordinal); CREATE INDEX cities_coordinates ON cities(latitude,longitude,ordinal); COMMIT; VACUUM;');
}finally{db.close();}
writeFileSync(new URL('city-database-asset.ts',new URL('../src/data/',import.meta.url)),`// Generated by scripts/build-city-database.mjs from the pinned GeoNames source.\nexport const CITY_DATABASE_NAME = '${name}';\nexport const CITY_DATABASE_ASSET = require('../../assets/cities/${name}');\n`);
console.log(`Prepared ${source.length} unchanged cities in ${name}`);
